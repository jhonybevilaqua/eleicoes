-- ---------- Domínios permitidos ----------------------------------------
create or replace function public.email_corporativo(e text)
returns boolean language sql immutable as $$
  select lower(coalesce(e, '')) ~ '@(tvevangelizar\.com\.br|evangelizarepreciso\.com\.br)$'
$$;

-- Bloqueia a criação de conta fora dos domínios (vale mesmo se alguém
-- chamar a API do Supabase direto, sem passar pela tela de login).
create or replace function public.bloquear_dominio()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if not public.email_corporativo(new.email) then
    raise exception 'Acesso restrito a e-mails @tvevangelizar.com.br e @evangelizarepreciso.com.br';
  end if;
  return new;
end $$;

drop trigger if exists bloquear_dominio on auth.users;
create trigger bloquear_dominio before insert or update of email on auth.users
  for each row execute function public.bloquear_dominio();

-- ---------- Usuários e papéis ------------------------------------------
-- admin    : tudo, inclusive usuários e importação da planilha
-- operador : cadastra, edita, registra saídas/devoluções e inspeções
-- leitor   : só consulta (padrão para quem não está na tabela)
create table if not exists public.usuarios (
  email      text primary key check (public.email_corporativo(email) and email = lower(email)),
  nome       text,
  papel      text not null default 'operador' check (papel in ('admin', 'operador', 'leitor')),
  created_at timestamptz not null default now()
);

create or replace function public.meu_email()
returns text language sql stable as $$
  select lower(coalesce(auth.jwt() ->> 'email', ''))
$$;

create or replace function public.meu_papel()
returns text language sql stable security definer set search_path = public as $$
  select case
    when not public.email_corporativo(public.meu_email()) then null
    when public.meu_email() = 'jhony.bevilaqua@tvevangelizar.com.br' then 'admin'   -- administrador geral, fixo
    else coalesce((select papel from public.usuarios where email = public.meu_email()), 'leitor')
  end
$$;

create or replace function public.pode_ler() returns boolean language sql stable as $$
  select public.email_corporativo(public.meu_email())
$$;
create or replace function public.pode_editar() returns boolean language sql stable as $$
  select public.meu_papel() in ('admin', 'operador')
$$;
create or replace function public.e_admin() returns boolean language sql stable as $$
  select public.meu_papel() = 'admin'
$$;

-- ---------- Itens -------------------------------------------------------
create table if not exists public.itens (
  id              bigint generated by default as identity primary key,
  equipamento     text not null,
  tipo            text not null default 'OUTROS',
  marca           text,
  modelo          text,
  descricao       text,
  numero_serie    text,
  patrimonio      text,
  codigo_almox    text,
  data_entrada    text,          -- como veio da planilha ("ANTERIOR A 2019", "25/08/2022"...)
  ano_entrada     int,
  vida_util_anos  int,
  localizacao     text,
  acessorios      text,
  observacoes     text,
  historico       text,          -- histórico livre herdado da planilha
  ultima_inspecao date,
  status          text not null default 'DISPONIVEL'
                  check (status in ('DISPONIVEL', 'EM_USO', 'MANUTENCAO', 'AVARIADO', 'BAIXADO')),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  updated_by      text
);
create index if not exists itens_tipo_idx on public.itens (tipo);
create index if not exists itens_status_idx on public.itens (status);
create index if not exists itens_local_idx on public.itens (localizacao);

-- ---------- Movimentações (saída / devolução) --------------------------
create table if not exists public.movimentacoes (
  id               bigint generated by default as identity primary key,
  item_id          bigint not null references public.itens (id) on delete cascade,
  lote             uuid not null default gen_random_uuid(),   -- itens que saíram juntos
  responsavel      text not null,
  setor            text,
  destino          text,
  saida_em         timestamptz not null default now(),
  previsao_retorno timestamptz,
  devolvido_em     timestamptz,
  condicao_retorno text check (condicao_retorno in ('OK', 'AVARIADO', 'MANUTENCAO')),
  obs_saida        text,
  obs_retorno      text,
  registrado_por   text default public.meu_email(),
  recebido_por     text
);
create unique index if not exists mov_uma_saida_aberta on public.movimentacoes (item_id) where devolvido_em is null;
create index if not exists mov_item_idx on public.movimentacoes (item_id);
create index if not exists mov_saida_idx on public.movimentacoes (saida_em desc);

-- ---------- Log de eventos ---------------------------------------------
create table if not exists public.eventos (
  id         bigint generated by default as identity primary key,
  item_id    bigint references public.itens (id) on delete set null,
  acao       text not null,
  detalhe    text,
  usuario    text default public.meu_email(),
  created_at timestamptz not null default now()
);
create index if not exists eventos_item_idx on public.eventos (item_id, created_at desc);
create index if not exists eventos_data_idx on public.eventos (created_at desc);

-- ---------- Triggers ----------------------------------------------------
create or replace function public.itens_carimbo()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  new.updated_by := nullif(public.meu_email(), '');
  return new;
end $$;
drop trigger if exists itens_carimbo on public.itens;
create trigger itens_carimbo before insert or update on public.itens
  for each row execute function public.itens_carimbo();

create or replace function public.itens_log()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  campos text;
begin
  if tg_op = 'INSERT' then
    insert into eventos (item_id, acao, detalhe) values (new.id, 'CADASTRO', new.equipamento);
  elsif tg_op = 'DELETE' then
    insert into eventos (item_id, acao, detalhe)
      values (null, 'EXCLUSÃO', old.equipamento || coalesce(' · cód. ' || old.codigo_almox, '') || coalesce(' · pat. ' || old.patrimonio, ''));
    return old;
  else
    select string_agg(n.key, ', ' order by n.key) into campos
      from jsonb_each(to_jsonb(new)) n
     where n.value is distinct from (to_jsonb(old) -> n.key)
       and n.key not in ('updated_at', 'updated_by', 'created_at');
    if campos is null or campos = 'status' and pg_trigger_depth() > 1 then
      return new;                       -- status mudado por saída/devolução já tem evento próprio
    elsif campos = 'ultima_inspecao' then
      insert into eventos (item_id, acao, detalhe) values (new.id, 'INSPEÇÃO', 'Inspeção registrada em ' || to_char(new.ultima_inspecao, 'DD/MM/YYYY'));
    elsif campos = 'status' then
      insert into eventos (item_id, acao, detalhe) values (new.id, 'STATUS', old.status || ' → ' || new.status);
    else
      insert into eventos (item_id, acao, detalhe) values (new.id, 'EDIÇÃO', 'Campos: ' || campos);
    end if;
  end if;
  return new;
end $$;
drop trigger if exists itens_log on public.itens;
create trigger itens_log after insert or update or delete on public.itens
  for each row execute function public.itens_log();

create or replace function public.mov_status()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    update itens set status = 'EM_USO' where id = new.item_id;
    insert into eventos (item_id, acao, detalhe)
      values (new.item_id, 'SAÍDA', 'Com ' || new.responsavel || coalesce(' (' || new.setor || ')', '') || coalesce(' · ' || new.destino, ''));
  elsif old.devolvido_em is null and new.devolvido_em is not null then
    new.recebido_por := coalesce(new.recebido_por, nullif(public.meu_email(), ''));
    update itens set status = case coalesce(new.condicao_retorno, 'OK')
                                when 'AVARIADO' then 'AVARIADO'
                                when 'MANUTENCAO' then 'MANUTENCAO'
                                else 'DISPONIVEL' end
     where id = new.item_id;
    insert into eventos (item_id, acao, detalhe)
      values (new.item_id, 'DEVOLUÇÃO', 'Condição: ' || coalesce(new.condicao_retorno, 'OK') || coalesce(' · ' || new.obs_retorno, ''));
  end if;
  return new;
end $$;
drop trigger if exists mov_status_ins on public.movimentacoes;
create trigger mov_status_ins after insert on public.movimentacoes
  for each row execute function public.mov_status();
drop trigger if exists mov_status_upd on public.movimentacoes;
create trigger mov_status_upd before update on public.movimentacoes
  for each row execute function public.mov_status();

